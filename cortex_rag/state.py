"""Pydantic schemas and LangGraph AgentState definitions for Cortex-Compliance."""

from enum import Enum
from typing import Any, Dict, List, Optional
from typing_extensions import TypedDict
from pydantic import BaseModel, Field


class SeverityLevel(str, Enum):
    CRITICAL = "critical"
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"
    INFO = "info"


class VerdictStatus(str, Enum):
    CONFIRMED_VIOLATION = "CONFIRMED_VIOLATION"
    FALSE_POSITIVE = "FALSE_POSITIVE"
    MITIGATED_EXTERNALLY = "MITIGATED_EXTERNALLY"
    NEEDS_HUMAN_REVIEW = "NEEDS_HUMAN_REVIEW"


class Stage1Finding(BaseModel):
    """Structured deterministic finding produced by Stage 1 SAST scanner."""

    finding_id: str = Field(description="Unique identifier for the finding instance")
    file_path: str = Field(description="Relative or absolute path to scanned file")
    line: int = Field(description="1-based line number of the match")
    rule_id: str = Field(description="Rule identifier, e.g. SEC-SQLI-01")
    category: str = Field(description="Category, e.g. Database Attacks, Secret Leak")
    title: str = Field(description="Human readable title of violation")
    severity: SeverityLevel = Field(default=SeverityLevel.HIGH)
    cwe: str = Field(default="")
    owasp: str = Field(default="")
    compliance_control: str = Field(default="")
    exploit: str = Field(default="")
    snippet: str = Field(description="Matching code snippet line or block")
    bad_code: str = Field(default="")
    good_code: str = Field(default="")


class PolicyCitation(BaseModel):
    """Regulatory citation retrieved from policies corpus."""

    policy_id: str = Field(description="Policy ID or filename, e.g. POL-GDPR-PRIVACY-V2")
    policy_title: str = Field(description="Title of policy document")
    section_or_article: str = Field(description="Specific clause, e.g. Article 8")
    text: str = Field(description="Extracted regulatory clause text")
    legal_risk: str = Field(default="")
    penalty_framework: str = Field(default="")
    relevance_score: float = Field(default=0.0, ge=0.0, le=1.0)
    is_graded_relevant: bool = Field(default=True)


class AgentVerdict(BaseModel):
    """Stage 2 agentic evaluation verdict."""

    finding_id: str
    status: VerdictStatus
    confidence: float = Field(ge=0.0, le=1.0)
    reason: str
    root_cause_analysis: str
    cross_file_impacts: List[str] = Field(default_factory=list)


class CodePatch(BaseModel):
    """Auto-remediation patch generated by Stage 2 Agent."""

    file_path: str
    start_line: int
    end_line: int
    original_code: str
    proposed_code: str
    patch_diff: str = Field(description="Unified diff format patch")
    auto_fix_safe: bool = True
    explanation: str = Field(default="")


class AuditFinding(BaseModel):
    """Full consolidated finding record with Stage 1 trigger, Citations, Verdict, and Patch."""

    stage1: Stage1Finding
    verdict: Optional[AgentVerdict] = None
    citations: List[PolicyCitation] = Field(default_factory=list)
    patch: Optional[CodePatch] = None


class ComplianceReport(BaseModel):
    """Complete audit telemetry report."""

    audit_id: str
    timestamp: str
    repo_name: str = "workspace"
    commit_sha: str = "HEAD"
    branch: str = "main"
    scan_summary: str
    health_score: int = Field(ge=0, le=100)
    total_findings: int
    confirmed_violations: int
    false_positives: int
    mitigated_count: int
    pipeline_steps: List[str] = Field(default_factory=list)
    findings: List[AuditFinding] = Field(default_factory=list)
    lancedb_synced: bool = False
    supabase_synced: bool = False


class AgentState(TypedDict, total=False):
    """State graph passed through LangGraph Corrective RAG nodes."""

    files_to_scan: List[str]
    raw_contents: Dict[str, str]
    stage1_findings: List[Dict[str, Any]]
    current_finding_index: int
    current_finding: Optional[Dict[str, Any]]
    retrieved_citations: List[Dict[str, Any]]
    graded_citations: List[Dict[str, Any]]
    cross_file_contexts: Dict[str, List[str]]
    current_verdict: Optional[Dict[str, Any]]
    verdicts: List[Dict[str, Any]]
    patches: List[Dict[str, Any]]
    iteration_count: int
    pipeline_steps: List[str]
    final_report: Optional[Dict[str, Any]]
